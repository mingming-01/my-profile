-- my-profile Passkey Private Space production schema.
-- Flask connects with a private PostgreSQL connection string.
-- Do not grant direct access to anon/authenticated roles.

CREATE TABLE IF NOT EXISTS users (
    username TEXT PRIMARY KEY,
    display_name TEXT NOT NULL,
    user_handle TEXT NOT NULL UNIQUE,
    invite_used_at TEXT,
    created_at TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS passkeys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    credential_id TEXT NOT NULL UNIQUE,
    username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,
    public_key TEXT NOT NULL,
    sign_count BIGINT NOT NULL DEFAULT 0,
    name TEXT NOT NULL,
    registered_at TEXT NOT NULL,
    last_used_at TEXT
);

CREATE TABLE IF NOT EXISTS auth_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_key TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS webauthn_challenges (
    challenge_hash TEXT PRIMARY KEY,
    ceremony TEXT NOT NULL,
    challenge TEXT NOT NULL,
    username TEXT NOT NULL,
    payload_json TEXT NOT NULL,
    created_at DOUBLE PRECISION NOT NULL,
    consumed_at DOUBLE PRECISION
);

CREATE INDEX IF NOT EXISTS idx_passkeys_username ON passkeys(username);
CREATE INDEX IF NOT EXISTS idx_auth_attempts_key_time ON auth_attempts(attempt_key, created_at);
CREATE INDEX IF NOT EXISTS idx_webauthn_challenges_created ON webauthn_challenges(created_at);

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE passkeys ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE webauthn_challenges ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE users, passkeys, auth_attempts, webauthn_challenges
FROM PUBLIC, anon, authenticated;
